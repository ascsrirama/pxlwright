const rows = (name: string) => art[name];
const mirror = (r: string[]) => r.map((s) => [...s].reverse().join(''));
const transpose = (r: string[]) => r[0].split('').map((_, c) => r.map((row) => row[c]).join(''));

art['arrow-left'] = mirror(rows('arrow-right'));
art['arrow-down'] = transpose(rows('arrow-right'));
// arrow-up = vertical flip of arrow-down
art['arrow-up'] = [...art['arrow-down']].reverse();

export interface IconDef {
  id: string;
  label: string;
  w: number;
  h: number;
  bits: number[];
}

export const ICONS: IconDef[] = Object.entries(art).map(([id, r]) => ({
  id,
  label: id.replace('-', ' '),
  w: 16,
  h: 16,
  bits: packBits(
    r.flatMap((row) => [...row].map((ch) => (ch === '#' ? 1 : 0))),
    16,
    16
  )
}));

export function iconById(id: string): IconDef {
  return ICONS.find((i) => i.id === id) ?? ICONS[0];
}

